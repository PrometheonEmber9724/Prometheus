"""Isolated Prometheus core service tests.

Uses a temporary SQLite database and never touches the showcase database.
"""

import os
from pathlib import Path
import tempfile
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TEST_DB = Path(tempfile.gettempdir()) / "prometheus_one_core_test.db"
try:
    TEST_DB.unlink(missing_ok=True)
except PermissionError:
    pass
os.environ["PROMETHEUS_DATABASE_URL"] = f"sqlite:///{TEST_DB.as_posix()}"

from database import init_database  # noqa: E402
from models import engine  # noqa: E402
from seed import DEMO_EMAIL, DEMO_PASSWORD, JUDGE_EMAIL, JUDGE_PASSWORD, SELLER_EMAIL, SELLER_PASSWORD, seed_demo_data  # noqa: E402
from services import (  # noqa: E402
    PrometheusServiceError,
    authenticate_user,
    buy_secondary_listing,
    create_secondary_listing,
    create_user,
    get_active_listings,
    get_audit_events,
    get_deal,
    get_deal_suitability,
    get_deals,
    get_holdings,
    get_market_revision,
    get_notifications,
    get_order_book,
    get_portfolio_intelligence,
    get_unread_notification_count,
    get_wallet,
    get_wallet_transactions,
    invest_in_deal,
    mark_all_notifications_read,
    run_scenario,
    set_demo_kyc_status,
)


def expect_error(fn, contains: str):
    try:
        fn()
    except PrometheusServiceError as exc:
        assert contains.lower() in str(exc).lower(), (contains, str(exc))
        return str(exc)
    raise AssertionError(f"Expected PrometheusServiceError containing: {contains}")


def main():
    init_database()
    seed_demo_data()

    deals = get_deals()
    assert len(deals) == 5
    solstice = next(d for d in deals if d.code == "SPV-014")

    demo = authenticate_user(DEMO_EMAIL, DEMO_PASSWORD)
    seller = authenticate_user(SELLER_EMAIL, SELLER_PASSWORD)
    judge = authenticate_user(JUDGE_EMAIL, JUDGE_PASSWORD)
    assert demo.id != seller.id != judge.id
    assert get_wallet(demo.id) == 15000.0
    assert get_wallet(seller.id) == 5000.0
    assert get_wallet(judge.id) == 20500.0
    assert len(get_holdings(judge.id)) == 5

    # Deal Room + Capital Timeline.
    detailed = get_deal(solstice.id)
    assert detailed.investment_thesis
    assert len(detailed.milestones) >= 4

    # Rules-based suitability context is educational, not predictive.
    suitability = get_deal_suitability(judge.id, solstice.id)
    assert suitability.risk_profile == "Balanced"
    assert suitability.deal_name == "Solstice Robotics"
    assert suitability.risk_fit in {"Aligned", "Above profile", "Within profile"}
    assert "not advice" in suitability.summary.lower() or "educational" in suitability.summary.lower()

    # Scenario Lab is deterministic and clearly separate from any predictive model.
    scenario = run_scenario(solstice.id, 5000, -10, 6)
    assert scenario.projected_value > 0
    assert scenario.exit_delay_months == 6
    assert "not a forecast" in scenario.disclaimer.lower()

    # V1/V2/V3 primary investment + wallet ownership.
    result = invest_in_deal(demo.id, solstice.id, 2)
    assert result.cost == 1000.0
    assert get_wallet(demo.id) == 14000.0
    assert get_wallet(seller.id) == 5000.0
    assert get_wallet(judge.id) == 20500.0
    assert len(get_holdings(judge.id)) == 5
    assert next(h for h in get_holdings(demo.id) if h.deal_id == solstice.id).units == 2

    # Portfolio intelligence is rules based.
    intel = get_portfolio_intelligence(demo.id)
    assert intel.holding_count == 1
    assert intel.sector_count == 1
    assert 0 <= intel.score <= 100
    assert intel.largest_sector == "Technology"

    # Notifications are generated by account activity.
    assert get_unread_notification_count(demo.id) >= 2
    notes = get_notifications(demo.id)
    assert any("Investment" in n.title for n in notes)
    marked = mark_all_notifications_read(demo.id)
    assert marked >= 1
    assert get_unread_notification_count(demo.id) == 0

    # Order book contains seeded indicative bids and real asks.
    book = get_order_book(solstice.id)
    assert len(book.bid_levels) >= 1
    assert len(book.ask_levels) >= 1
    assert book.best_bid is not None
    assert book.best_ask is not None

    # V4 trade remains atomic and creates notifications/audits.
    listing = create_secondary_listing(demo.id, solstice.id, 1, 510)
    before_seller = get_wallet(seller.id)
    trade = buy_secondary_listing(seller.id, listing.listing_id)
    assert trade.gross_amount == 510.0
    assert get_wallet(seller.id) == before_seller - 510.0
    assert get_wallet(demo.id) > 14000.0  # seller proceeds net of fee
    assert any(h.deal_id == solstice.id for h in get_holdings(seller.id))
    assert any(a.event_type == "secondary_sale" for a in get_audit_events(demo.id))
    assert any(a.event_type == "secondary_purchase" for a in get_audit_events(seller.id))

    revision = get_market_revision()
    assert revision.active_listings >= 1
    assert revision.active_bids >= 1
    assert revision.completed_trades >= 1

    # New-user ownership + KYC guard still works.
    newcomer = create_user("Prometheus New Investor", "po-new@example.com", "POneStrongPassword!", "Conservative")
    expect_error(lambda: invest_in_deal(newcomer.id, solstice.id, 1), "KYC")
    set_demo_kyc_status(newcomer.id, "verified")
    invest_in_deal(newcomer.id, solstice.id, 1)
    assert get_wallet(newcomer.id) == 14500.0

    # Security hardening: temporary lock after repeated bad passwords.
    create_user("Security Test", "security-test@example.com", "SecurityPass123!", "Balanced")
    for _ in range(4):
        expect_error(lambda: authenticate_user("security-test@example.com", "wrong-password"), "attempt")
    expect_error(lambda: authenticate_user("security-test@example.com", "wrong-password"), "locked")
    expect_error(lambda: authenticate_user("security-test@example.com", "SecurityPass123!"), "try again")

    # Wallet remains append-only and deal data stays isolated from failed auth.
    assert len(get_wallet_transactions(demo.id)) >= 3
    assert len(get_active_listings()) >= 1

    print("PASS — Prometheus core services, security, Deal Room, portfolio and secondary market are working.")


if __name__ == "__main__":
    try:
        main()
    finally:
        engine.dispose()
        try:
            TEST_DB.unlink(missing_ok=True)
        except PermissionError:
            print(f"NOTE — Windows still has the temporary test DB open: {TEST_DB}")
